import io
import urllib.error
import zipfile

import pytest
from botocore.exceptions import BotoCoreError
from pytest_mock import MockerFixture

from src.citibike_historical_client import CitiBikeHistoricalClient


class TestCitiBikeHistoricalClient:

    @pytest.fixture
    def mock_s3_service(self, mocker: MockerFixture):
        """Mock the S3Service dependency to avoid real AWS calls."""
        return mocker.MagicMock()

    @pytest.fixture
    def subject(self, mock_s3_service) -> CitiBikeHistoricalClient:
        """Inject dependencies into the client subject."""
        return CitiBikeHistoricalClient(
            s3_service=mock_s3_service,
            user_agent="TestAgent/1.0"
        )

    @pytest.fixture
    def valid_zip_buffer(self):
        """Creates a realistic in-memory zip file with mixed content for testing."""
        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, 'w') as zf:
            zf.writestr('202609-citibike-tripdata.csv', 'col1,col2\n1,2')
            zf.writestr('__MACOSX/._202609-citibike-tripdata.csv', 'hidden file info')
            zf.writestr('readme.txt', 'document info')
            zf.writestr('extra_data.csv', 'col1,col2\n3,4')
        
        # Reset pointer to the beginning of the stream before yielding
        buffer.seek(0)
        return buffer

    def test_extract_zip_happy_path_returns_object(self, mocker: MockerFixture, subject: CitiBikeHistoricalClient):
        """Verify URL extraction correctly formats and returns a BytesIO object."""
        mock_urlopen = mocker.patch("urllib.request.urlopen")
        mock_response = mocker.MagicMock()
        mock_response.read.return_value = b"fake_zip_bytes"
        mock_response.__enter__.return_value = mock_response 
        mock_urlopen.return_value = mock_response

        result = subject.extract_zip("http://example.com/data.zip")

        assert isinstance(result, io.BytesIO)
        assert result.read() == b"fake_zip_bytes"
        
        # Ensure the Request was created with the correct User-Agent
        req_arg = mock_urlopen.call_args[0][0]
        assert req_arg.headers == {"User-agent": "TestAgent/1.0"}

    def test_extract_zip_file_error_returns_null(self, mocker: MockerFixture, subject: CitiBikeHistoricalClient):
        """Verify URLErrors are caught safely and return None."""
        mock_urlopen = mocker.patch("urllib.request.urlopen")
        mock_urlopen.side_effect = urllib.error.URLError("Not Found")

        result = subject.extract_zip("http://example.com/data.zip")

        assert result is None
        mock_urlopen.assert_called_once()

    def test_write_csvs_to_s3_happy_path_returns_count(
        self, mocker: MockerFixture, subject: CitiBikeHistoricalClient, mock_s3_service, valid_zip_buffer
    ):
        """Verify the zip parser successfully ignores non-CSV and MacOSX files, returning accurate counts."""
        s3_prefix = "bronze/trips/year=2026/month=09"
        
        count = subject.write_csvs_to_s3(valid_zip_buffer, s3_prefix)

        # Out of the 4 files in the fixture, only 2 are valid CSVs
        assert count == 2
        assert mock_s3_service.write_csv_file_object.call_count == 2
        
        # Verify the exact S3 keys generated by the client
        mock_s3_service.write_csv_file_object.assert_any_call(
            mocker.ANY, f"{s3_prefix}/202609-citibike-tripdata.csv"
        )
        mock_s3_service.write_csv_file_object.assert_any_call(
            mocker.ANY, f"{s3_prefix}/extra_data.csv"
        )

    def test_write_csvs_to_s3_failed_file_returns_0(self, subject: CitiBikeHistoricalClient, mock_s3_service):
        """Verify BadZipFile errors are caught and 0 is returned."""
        # Provide invalid bytes that cannot be read as a zip
        invalid_zip_buffer = io.BytesIO(b"not a valid zip file format")
        
        count = subject.write_csvs_to_s3(invalid_zip_buffer, "bronze/trips")

        assert count == 0
        mock_s3_service.write_csv_file_object.assert_not_called()

    def test_write_csvs_to_s3_boto_error_returns_0(self, subject: CitiBikeHistoricalClient, mock_s3_service, valid_zip_buffer):
        """Verify BotoCoreErrors during S3 upload are caught gracefully."""
        mock_s3_service.write_csv_file_object.side_effect = BotoCoreError()
        
        count = subject.write_csvs_to_s3(valid_zip_buffer, "bronze/trips")

        assert count == 0